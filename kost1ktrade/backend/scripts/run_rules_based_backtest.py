def main(asset: str, timeframe: str):
    """
    Main orchestration script for backtesting a rules-based strategy.
    """
    print(f"--- Starting Rules-Based Backtest for {asset} on {timeframe} ---")

    db: Session = SessionLocal()
    try:
        # 1. Load and process data to get core features
        raw_df = load_data_from_db(db, asset, timeframe)
        if raw_df.empty:
            print("No data loaded, cannot proceed.")
            return

        df_for_features = raw_df.reset_index().rename(columns={'timestamp': 'open_time'})
        features_df = create_core_features(df_for_features)

        # 2. Instantiate the strategy
        strategy = HierarchicalQuartetStrategy()

        # 3. Generate signals
        signals_df = strategy.generate_signals(features_df)

        # 4. Run the backtest simulation
        run_backtest_simulation(signals_df)

    finally:
        db.close()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description="Rules-Based Backtesting Orchestrator")
    parser.add_argument("--asset", type=str, default="BTC", help="The crypto asset to process.")
    parser.add_argument("--timeframe", type=str, default="4h", help="The OHLCV timeframe to use.")
    args = parser.parse_args()

    main(asset=args.asset, timeframe=args.timeframe)

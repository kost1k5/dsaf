def run_backtest_simulation(signals_df: pd.DataFrame):
    """
    Runs a simple backtest simulation based on BUY/SELL signals.
    Borrows logic from the original evaluate_model.py script.
    """
    print("\n--- Running Backtest Simulation ---")
    s = settings.EVAL
    capital = s.INITIAL_CAPITAL
    equity_curve = [s.INITIAL_CAPITAL]
    trades_list = []
    position = 0 # -1 for short, 1 for long, 0 for flat

    for i in range(len(signals_df)):
        row = signals_df.iloc[i]

        # --- Exit Logic ---
        if position != 0:
            entry_price = trades_list[-1]['entry_price']
            pnl_ratio = (row['close'] - entry_price) / entry_price
            if position == -1: pnl_ratio = -pnl_ratio

            # Simple exit: exit on the next bar for now.
            # A more advanced version would use ATR-based stops.
            net_pnl = capital * pnl_ratio * s.RISK_PER_TRADE # Simplified PnL
            capital += net_pnl
            equity_curve.append(capital)
            trades_list[-1]['exit_price'] = row['close']
            trades_list[-1]['pnl'] = net_pnl
            position = 0

        # --- Entry Logic ---
        if row['signal'] == 'BUY' and position == 0:
            position = 1
            trades_list.append({'entry_price': row['close'], 'signal': 'BUY'})
        elif row['signal'] == 'SELL' and position == 0:
            position = -1
            trades_list.append({'entry_price': row['close'], 'signal': 'SELL'})

    if not trades_list:
        print("No trades were generated by the strategy.")
        return None

    # --- Final Metrics Calculation ---
    total_trades = len(trades_list)
    wins = sum(1 for t in trades_list if t.get('pnl', 0) > 0)
    win_rate = wins / total_trades if total_trades > 0 else 0

    equity_ser = pd.Series(equity_curve)
